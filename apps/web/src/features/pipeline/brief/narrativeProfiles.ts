export function narrativeProfilePrompt(profile: NarrativeProfile) {
  const lines = (items: string[]) => items.map((item) => `- ${item}`).join('\n');
  return `## 用户选择的叙事角色（只读）\n- 角色：${profile.name}｜${profile.role}\n- 职责：${profile.mission}\n\n### 叙事原则\n${lines(profile.principles)}\n\n### 创作自由\n${lines(profile.creativeLatitude)}\n\n### 不可越界\n${lines(profile.boundaries)}\n\n该角色只决定观察、取舍与表达策略；阶段 Artifact、Canon、人物知识边界、SceneContract 和用户明确要求始终优先。不要模仿任何具体作家的可识别文风。`;
}
